#!/usr/bin/env python3
"""Generate a Harbor task from specs/<name>/spec.toml.

Usage: scripts/make_task.py <name> [<name> ...]

The generated tasks/<name>/ is fully overwritten (it is a build artifact).
Stdlib only, Python >= 3.11.
"""
import io
import json
import re
import shlex
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_BASE_IMAGE = "ubuntu:24.04"
SHA_RE = re.compile(r"^[0-9a-f]{40}$")


def die(msg: str) -> None:
    sys.exit(f"make_task: {msg}")


def git(*args: str, cwd: Path, capture: bool = False) -> bytes:
    res = subprocess.run(
        ["git", *args], cwd=cwd, capture_output=True, check=False
    )
    if res.returncode != 0:
        die(f"git {' '.join(args)} failed: {res.stderr.decode().strip()}")
    return res.stdout


def fetch_tree(source: dict, spec_dir: Path, dest: Path) -> None:
    """Extract source.repo at source.revision (optionally a subdir) into dest."""
    revision = source["revision"]
    if not SHA_RE.match(revision):
        die(
            f"source.revision must be a full 40-hex SHA, got {revision!r} "
            "(resolve a branch with `git ls-remote <repo> <branch>`)"
        )
    repo = source["repo"]
    local = (spec_dir / repo).resolve()
    if local.exists():
        repo = str(local)

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        git("init", "-q", cwd=work)
        # Shallow fetch of the single revision: no other history is ever copied.
        git("fetch", "-q", "--depth", "1", repo, revision, cwd=work)
        tree = f"FETCH_HEAD:{source['subdir']}" if source.get("subdir") else "FETCH_HEAD"
        archive = git("archive", "--format=tar", tree, cwd=work)

    dest.mkdir(parents=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        tar.extractall(dest, filter="data")


def patch_files(patch: Path) -> list[str]:
    """Paths touched by a patch (from git apply --numstat)."""
    # Run outside any repo: inside one, git apply skips paths outside the cwd prefix.
    with tempfile.TemporaryDirectory() as tmp:
        out = subprocess.run(
            ["git", "apply", "--numstat", "-z", str(patch.resolve())],
            cwd=tmp, capture_output=True, check=False,
        )
    if out.returncode != 0:
        die(f"invalid patch {patch}: {out.stderr.decode().strip()}")
    files = []
    for rec in out.stdout.decode().split("\0"):
        parts = rec.split("\t")
        if len(parts) == 3:
            files.append(parts[2])
    return files


def render_dockerfile(spec: dict, has_setup: bool) -> str:
    env = spec["environment"]
    packages = " ".join(shlex.quote(p) for p in env.get("packages", []))
    pip = " ".join(shlex.quote(p) for p in env.get("pip", []))
    lines = [
        f"# GENERATED by scripts/make_task.py from specs/{spec['name']}/spec.toml. Do not edit.",
        f"FROM {env.get('base_image', DEFAULT_BASE_IMAGE)}",
        "",
        "# System packages (spec: environment.packages) plus the tools every task needs",
        "# (git, bash) when the base image lacks them. The package manager is detected,",
        "# so Debian/Ubuntu, Alpine and RHEL-family images all work (see README: CA shim).",
        "RUN set -eu; \\",
        f'    pkgs="{packages}"; \\',
        '    command -v git >/dev/null 2>&1 || pkgs="git $pkgs"; \\',
        '    command -v bash >/dev/null 2>&1 || pkgs="bash $pkgs"; \\',
        '    if [ -n "${pkgs# }" ]; then \\',
        "        if command -v apt-get >/dev/null 2>&1; then \\",
        "            apt-get update \\",
        "            && apt-get install -y --no-install-recommends $pkgs \\",
        "            && rm -rf /var/lib/apt/lists/*; \\",
        "        elif command -v apk >/dev/null 2>&1; then \\",
        "            apk add --no-cache $pkgs; \\",
        "        elif command -v dnf >/dev/null 2>&1; then \\",
        "            dnf install -y $pkgs && dnf clean all; \\",
        "        elif command -v microdnf >/dev/null 2>&1; then \\",
        "            microdnf install -y $pkgs && microdnf clean all; \\",
        "        elif command -v yum >/dev/null 2>&1; then \\",
        "            yum install -y $pkgs && yum clean all; \\",
        "        else \\",
        '            echo "no supported package manager to install: $pkgs" >&2; exit 1; \\',
        "        fi; \\",
        "    fi",
        "",
    ]
    if pip:
        lines += [
            "# Python packages (spec: environment.pip); the base image must provide",
            "# python3 and pip. PIP_BREAK_SYSTEM_PACKAGES: Debian/Ubuntu images mark the",
            "# system Python as externally managed (PEP 668); the container is disposable.",
            "RUN python3 -m pip --version >/dev/null 2>&1 \\",
            '    || { echo "environment.pip requires python3 and pip in the base image" >&2; exit 1; }',
            f"RUN PIP_BREAK_SYSTEM_PACKAGES=1 python3 -m pip install --no-cache-dir {pip}",
            "",
        ]
    lines += [
        "COPY app/ /app/",
        "WORKDIR /app",
        "",
    ]
    if has_setup:
        lines += [
            "# Codebase preparation (spec: source.setup), before the baseline commit.",
            "COPY setup.sh /tmp/setup.sh",
            "RUN bash /tmp/setup.sh && rm -f /tmp/setup.sh",
            "",
        ]
    lines += [
        "# Single baseline commit: no upstream history, no remote, no fix in the repo.",
        "RUN git init -q \\",
        '    && git config user.name "harbor-sandbox" \\',
        '    && git config user.email "harbor-sandbox@example.invalid" \\',
        "    && git add -A \\",
        '    && git commit -q -m "initial import"',
        "",
    ]
    return "\n".join(lines)


def render_task_toml(spec: dict) -> str:
    lim, env, meta = spec["limits"], spec["environment"], spec.get("metadata", {})
    tags = ", ".join(json.dumps(t) for t in meta.get("tags", []))
    return f"""# GENERATED by scripts/make_task.py from specs/{spec['name']}/spec.toml. Do not edit.
schema_version = "1.4"

[metadata]
difficulty = {json.dumps(meta.get('difficulty', 'unknown'))}
category = {json.dumps(meta.get('category', 'unknown'))}
tags = [{tags}]

[verifier]
timeout_sec = {float(lim['verifier_timeout_sec'])}

[agent]
timeout_sec = {float(lim['agent_timeout_sec'])}

[environment]
build_timeout_sec = {float(lim['build_timeout_sec'])}
cpus = {env['cpus']}
memory_mb = {env['memory_mb']}
storage_mb = {env['storage_mb']}
"""


def render_limits_env(spec: dict) -> str:
    lim = spec["limits"]
    lines = [f"# GENERATED by scripts/make_task.py from specs/{spec['name']}/spec.toml."]
    if "max_turns" in lim:
        lines.append(f"MAX_TURNS={int(lim['max_turns'])}")
    if "max_budget_usd" in lim:
        lines.append(f"MAX_BUDGET_USD={shlex.quote(str(lim['max_budget_usd']))}")
    return "\n".join(lines) + "\n"


def render_test_sh(spec: dict, touched: list[str]) -> str:
    t = spec["tests"]
    cmd = t["command"]
    f2p = " ".join(shlex.quote(p) for p in t["f2p"])
    p2p = " ".join(shlex.quote(p) for p in t["p2p"])
    reset = "\n".join(
        f'    git checkout -q HEAD -- {shlex.quote(f)} 2>/dev/null || rm -f {shlex.quote(f)}'
        for f in touched
    )
    return f"""#!/bin/bash
# GENERATED by scripts/make_task.py from specs/{spec['name']}/spec.toml. Do not edit.
# Verifier: hidden FAIL_TO_PASS tests + PASS_TO_PASS tests.
# No "set -e": the reward file must always be written.

REWARD_DIR=/logs/verifier
mkdir -p "$REWARD_DIR"

f2p=0
p2p=0

if cd /app; then
    # Reset every file the test patch touches (the agent may have edited or
    # created them), then apply the hidden tests.
{reset}
    if git apply /tests/tests.patch; then
        echo "=== FAIL_TO_PASS (hidden tests) ==="
        if {cmd} {f2p}; then
            f2p=1
        fi

        echo "=== PASS_TO_PASS ==="
        if {cmd} {p2p}; then
            p2p=1
        fi
    else
        echo "Cannot apply /tests/tests.patch" >&2
    fi
else
    echo "Cannot cd into /app" >&2
fi

resolved=$((f2p * p2p))
printf '{{"resolved": %d, "f2p": %d, "p2p": %d}}\\n' "$resolved" "$f2p" "$p2p" \\
    > "$REWARD_DIR/reward.json"
cat "$REWARD_DIR/reward.json"
exit 0
"""


def render_solve_sh(spec: dict) -> str:
    return f"""#!/bin/bash
# GENERATED by scripts/make_task.py from specs/{spec['name']}/spec.toml. Do not edit.
# Reference fix (oracle agent).
set -euo pipefail

cd /app
git apply "$(dirname "$0")/fix.patch"
"""


def write(path: Path, content: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    if executable:
        path.chmod(0o755)


def make_task(name: str) -> None:
    spec_dir = ROOT / "specs" / name
    spec_file = spec_dir / "spec.toml"
    if not spec_file.is_file():
        die(f"no spec at {spec_file}")
    spec = tomllib.loads(spec_file.read_text())
    if spec["name"] != name:
        die(f"spec name {spec['name']!r} does not match directory {name!r}")

    def rel(key_path: str) -> Path:
        p = spec_dir / key_path
        if not p.is_file():
            die(f"missing file referenced by spec: {p}")
        return p

    instruction = rel(spec["instruction"])
    tests_patch = rel(spec["tests"]["patch"])
    fix_patch = rel(spec["solution"]["patch"])
    setup = rel(spec["source"]["setup"]) if "setup" in spec["source"] else None
    touched = patch_files(tests_patch)

    out = ROOT / "tasks" / name
    if out.exists():
        shutil.rmtree(out)
    fetch_tree(spec["source"], spec_dir, out / "environment" / "app")
    if setup:
        shutil.copy(setup, out / "environment" / "setup.sh")

    write(out / "environment" / "Dockerfile", render_dockerfile(spec, setup is not None))
    write(out / "task.toml", render_task_toml(spec))
    write(out / "limits.env", render_limits_env(spec))
    shutil.copy(instruction, out / "instruction.md")
    (out / "tests").mkdir()
    shutil.copy(tests_patch, out / "tests" / "tests.patch")
    write(out / "tests" / "test.sh", render_test_sh(spec, touched), executable=True)
    (out / "solution").mkdir()
    shutil.copy(fix_patch, out / "solution" / "fix.patch")
    write(out / "solution" / "solve.sh", render_solve_sh(spec), executable=True)
    print(f"generated tasks/{name} (revision {spec['source']['revision'][:12]})")


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    for name in sys.argv[1:]:
        make_task(name)


if __name__ == "__main__":
    main()
